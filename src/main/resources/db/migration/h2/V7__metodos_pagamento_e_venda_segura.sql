-- 2. Tabela metodos_pagamento
CREATE TABLE metodos_pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    nome VARCHAR(50) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    ativo BOOLEAN DEFAULT TRUE NOT NULL,
    ordem INT DEFAULT 0 NOT NULL,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_metodo_tipo CHECK (tipo IN ('DINHEIRO', 'DIGITAL', 'FIADO')),
    CONSTRAINT uk_metodos_usuario_nome UNIQUE (usuario_id, nome),
    CONSTRAINT fk_metodos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

CREATE INDEX idx_metodos_pagamento_usuario ON metodos_pagamento(usuario_id, ordem);

