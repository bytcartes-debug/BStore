-- 4. Actualizar pagamentos_venda com metodo_id e referencia
ALTER TABLE pagamentos_venda ADD COLUMN metodo_id BIGINT;
ALTER TABLE pagamentos_venda ADD COLUMN referencia VARCHAR(100);

UPDATE pagamentos_venda pv
SET metodo_id = (
    SELECT mp.id FROM metodos_pagamento mp
    WHERE mp.usuario_id = pv.usuario_id
      AND (
        (pv.metodo = 'DINHEIRO' AND mp.nome = 'Dinheiro') OR
        (pv.metodo = 'MPESA' AND mp.nome = 'M-Pesa') OR
        (pv.metodo = 'EMOLA' AND mp.nome = 'e-Mola') OR
        (pv.metodo = 'MKESH' AND mp.nome = 'mKesh') OR
        (pv.metodo = 'CARTAO' AND mp.nome = 'Cartão') OR
        (pv.metodo = 'FIADO' AND mp.nome = 'A fiado')
      )
    LIMIT 1
);

ALTER TABLE pagamentos_venda ADD CONSTRAINT fk_pagamentos_venda_metodo 
